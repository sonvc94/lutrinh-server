// Regenerate src/api/schema.d.ts from the server's OpenAPI document (page 04 §F: generated, never
// hand-edited). The server does not need to run: the document is dumped from `create_app()`
// with an in-memory database. `--from http://127.0.0.1:8000/openapi.json` reads a running one.
import { execFileSync } from 'node:child_process'
import { existsSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const admin = join(dirname(fileURLToPath(import.meta.url)), '..')
const server = join(admin, '..', 'server')
const out = join(admin, 'src', 'api')

const DUMP = `
import json, sys
from sqlalchemy import create_engine
from lutrinh.api.app import create_app
from lutrinh.config import Settings
app = create_app(Settings(), engine=create_engine("sqlite://"))
sys.stdout.write(json.dumps(app.openapi(), ensure_ascii=False, indent=1, sort_keys=True))
`

function uv() {
  const tmp = process.env.LUTRINH_TMP ?? '/Volumes/wdblack/tmp/lutrinh-server'
  const local = join(tmp, 'uv-venv', 'bin', 'uv')
  return existsSync(local) ? local : 'uv'
}

async function document() {
  const i = process.argv.indexOf('--from')
  if (i > 0) {
    const res = await fetch(process.argv[i + 1])
    if (!res.ok) throw new Error(`GET openapi.json: ${res.status}`)
    return await res.text()
  }
  return execFileSync(uv(), ['run', '--quiet', 'python', '-c', DUMP], {
    cwd: server,
    encoding: 'utf8',
    maxBuffer: 32 * 1024 * 1024,
  })
}

const json = await document()
writeFileSync(join(out, 'openapi.json'), json + '\n')
const ast = await openapiTS(JSON.parse(json))
const banner = '// Generated by `npm run gen:api` from the server /openapi.json. Do not edit.\n'
writeFileSync(join(out, 'schema.d.ts'), banner + astToString(ast))
console.log('wrote src/api/openapi.json and src/api/schema.d.ts')
